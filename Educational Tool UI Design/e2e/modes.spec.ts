import { expect, test, type Page } from '@playwright/test'
import { audit, normalizeState, openWorkbench, readState, referenceDesign, runTest, tabTo } from './helpers'

async function keyboardMode(page: Page, mode: 'guided' | 'parametric') {
  const select = page.getByRole('combobox', { name: 'Interaction mode' })
  await tabTo(page, select)
  await select.press(mode === 'parametric' ? 'End' : 'Home')
  await select.press('Tab')
  await expect(select).toHaveValue(mode)
}

test('Guided and Parametric differ while keyboard switching and reload preserve the workspace', async ({ page }) => {
  test.setTimeout(90_000) // Real keyboard traversal plus reload, both modes and axe.
  await openWorkbench(page)
  const guide = page.getByRole('region', { name: 'Guided instructions' })
  await expect(guide.getByRole('heading', { name: 'Inspect', exact: true })).toBeVisible()
  await guide.getByRole('button', { name: '2. Experiment' }).click()
  await guide.getByText('Hint & suggested experiment').click()
  await expect(guide.getByText(/Try a diameter change/)).toBeVisible()
  await referenceDesign(page)
  await runTest(page)
  await expect(guide.getByRole('heading', { name: 'Compare', exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Compare Iteration 1', exact: true }).check()
  await page.getByRole('button', { name: 'Explain & submit', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Explain & submit', exact: true })
  await dialog.getByRole('textbox').fill('Mode switching keeps my tested design and reflection.')
  await dialog.getByRole('button', { name: 'Submit design & reflection' }).click()
  await page.keyboard.press('Escape')
  const before = await readState(page)
  await page.getByRole('region', { name: 'Design view' }).evaluate((element) => { element.setAttribute('data-mode-retained', 'yes') })
  await keyboardMode(page, 'parametric')
  await expect(guide).toHaveCount(0)
  await expect(page.getByRole('list', { name: 'Workflow' })).toHaveCount(0)
  expect(normalizeState(await readState(page))).toEqual(normalizeState({ ...before, mode: 'parametric' }))
  await expect(page.getByRole('region', { name: 'Design view' })).toHaveAttribute('data-mode-retained', 'yes')
  await audit(page)
  await page.reload()
  await openWorkbench(page, false)
  await expect(page.getByRole('combobox', { name: 'Interaction mode' })).toHaveValue('parametric')
  expect(normalizeState(await readState(page))).toEqual(normalizeState({ ...before, mode: 'parametric' }))
  await keyboardMode(page, 'guided')
  await expect(guide.getByRole('heading', { name: 'Explain', exact: true })).toBeVisible()
  expect(normalizeState(await readState(page))).toEqual(normalizeState(before))
  await page.setViewportSize({ width: 320, height: 1000 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await audit(page)
})

test('Parametric retains prediction checkpoints and mode guidance works with the SVG fallback', async ({ page }) => {
  await page.addInitScript(() => { Object.defineProperty(window, 'WebGL2RenderingContext', { configurable: true, value: undefined }) })
  await openWorkbench(page)
  await expect(page.locator('canvas')).toHaveCount(0)
  await keyboardMode(page, 'parametric')
  await referenceDesign(page)
  await page.getByRole('button', { name: 'Run Test', exact: true }).click()
  const prediction = page.getByRole('dialog', { name: 'Predict deflection' })
  await expect(prediction).toBeVisible()
  expect((await readState(page)).history).toHaveLength(1)
  await prediction.getByLabel('Decrease', { exact: true }).check()
  await prediction.getByRole('button', { name: 'Run structural test' }).click()
  await expect(prediction).toBeHidden()
  const before = await readState(page)
  expect(before.history).toHaveLength(2)
  expect(before.history[1].prediction?.direction).toBe('decrease')
  await keyboardMode(page, 'guided')
  await expect(page.getByRole('region', { name: 'Guided instructions' })).toBeVisible()
  expect(normalizeState(await readState(page))).toEqual(normalizeState({ ...before, mode: 'guided' }))
  await audit(page)
})
