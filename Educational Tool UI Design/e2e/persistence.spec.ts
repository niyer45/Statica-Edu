import { expect, test } from '@playwright/test'
import { audit, normalizeState, openWorkbench, readState, referenceDesign, runTest } from './helpers'

test('reload restores reflection/submission; import/export round-trips; corrupt saves restart with notice', async ({ page }) => {
  await openWorkbench(page)
  await referenceDesign(page)
  await runTest(page)
  await page.getByRole('button', { name: 'Explain & submit' }).click()
  await page.getByRole('dialog', { name: 'Explain & submit', exact: true }).getByRole('textbox').fill('I changed the section distribution.')
  await page.getByRole('button', { name: 'Submit design & reflection' }).click()
  await page.keyboard.press('Escape')
  const before = normalizeState(await readState(page))
  await page.reload()
  await openWorkbench(page, false)
  expect(normalizeState(await readState(page))).toEqual(before)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export design', exact: true }).click()
  const download = await downloadPromise
  const path = await download.path()
  if (!path) throw new Error('Design download not available')
  await page.getByLabel('Import design', { exact: true }).setInputFiles(path)
  await expect(page.getByTestId('live-region')).toContainText('Design imported')
  const afterImport = await readState(page)
  expect(afterImport.history).toHaveLength(2)
  const secondDownloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export design', exact: true }).click()
  const second = await secondDownloadPromise
  const secondPath = await second.path()
  if (!secondPath) throw new Error('Second design download missing')
  await page.getByLabel('Import design', { exact: true }).setInputFiles(secondPath)
  await expect(page.getByTestId('live-region')).toContainText('Design imported')
  expect((await readState(page)).draft).toEqual(afterImport.draft)
  await audit(page)
  await page.evaluate(() => localStorage.setItem('ei:session:cantilever-beam-1:v1', '{invalid'))
  await page.reload()
  await openWorkbench(page, false)
  await expect(page.getByTestId('live-region')).toContainText('Saved session could not be restored')
  expect((await readState(page)).history).toHaveLength(1)
  await audit(page)
})
