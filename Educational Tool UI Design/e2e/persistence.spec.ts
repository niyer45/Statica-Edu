import { expect, test } from '@playwright/test'
import { audit, normalizeState, openWorkbench, readState, referenceDesign, runTest } from './helpers'

test('reload restores reflection/submission; import/export round-trips; corrupt saves restart with notice', async ({ page }) => {
  await openWorkbench(page)
  await referenceDesign(page)
  await runTest(page)
  await page.getByRole('button', { name: 'Explain & submit' }).click()
  await page.getByRole('dialog', { name: 'Explain & submit', exact: true }).getByRole('textbox').fill('I changed the section distribution.')
  await page.getByRole('button', { name: 'Submit design & reflection' }).click()
  await page.keyboard.press('Escape')
  const saved = await readState(page)
  const before = normalizeState(saved)
  await page.reload()
  await openWorkbench(page, false)
  expect(normalizeState(await readState(page))).toEqual(before)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export design', exact: true }).click()
  const download = await downloadPromise
  const path = await download.path()
  if (!path) throw new Error('Design download not available')
  await page.getByLabel('Import design', { exact: true }).setInputFiles(path)
  await expect(page.getByTestId('live-region')).toContainText('Design imported')
  const afterImport = await readState(page)
  expect(afterImport.history).toEqual(saved.history)
  expect(afterImport.draft.section).toEqual(saved.draft.section)
  const secondDownloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export design', exact: true }).click()
  const second = await secondDownloadPromise
  const secondPath = await second.path()
  if (!secondPath) throw new Error('Second design download missing')
  await page.getByLabel('Import design', { exact: true }).setInputFiles(secondPath)
  await expect(page.getByTestId('live-region')).toContainText('Design imported')
  expect((await readState(page)).draft).toEqual(afterImport.draft)
  await audit(page)
  // Version 2 content (task 59) saves under the :v2 key.
  await page.evaluate(() => localStorage.setItem('ei:session:cantilever-beam-1:v2', '{invalid'))
  await page.reload()
  await openWorkbench(page, false)
  await expect(page.getByTestId('live-region')).toContainText('Saved session could not be restored')
  expect((await readState(page)).history).toHaveLength(1)
  await audit(page)
})


test('a save under the previous content version key is ignored without a notice and left in place', async ({ page }) => {
  // Task 59 moved Cantilever Beam I to content version 2 (new baseline), so saves use the :v2 key.
  // A version 1 save is never re-scored against the new content; a rollback can still read it.
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('ei:session:cantilever-beam-1:v1', '{"schemaVersion":1}'))
  await openWorkbench(page)
  const state = await readState(page)
  expect(state.challengeVersion).toBe(2)
  expect(state.history).toHaveLength(1)
  expect(state.draft.section.kind).toBe('iSection')
  await expect(page.getByTestId('live-region')).not.toContainText('Saved session could not be restored')
  expect(await page.evaluate(() => localStorage.getItem('ei:session:cantilever-beam-1:v1'))).toBe('{"schemaVersion":1}')
})

test('deleting an iteration confirms, persists after reload and removes comparison membership', async ({ page }) => {
  await openWorkbench(page)
  await referenceDesign(page)
  await runTest(page)
  await runTest(page)
  const before = await readState(page)
  const removed = before.history[1]!
  await expect(page.getByRole('button', { name: 'Delete Baseline', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Delete Iteration 1', exact: true }).click()
  await page.getByRole('dialog', { name: 'Delete Iteration 1?' }).getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Delete Iteration 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Delete Iteration 1', exact: true }).click()
  await page.getByRole('dialog', { name: 'Delete Iteration 1?' }).getByRole('button', { name: 'Delete iteration', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Delete Iteration 1', exact: true })).toHaveCount(0)
  const after = await readState(page)
  expect(after.draft).toEqual(before.draft)
  expect(after.history).toEqual(before.history)
  expect(after.compareSelection).not.toContain(removed.id)
  expect(after.deletedIterationIds).toContain(removed.id)
  await page.reload()
  await openWorkbench(page, false)
  await expect(page.getByRole('button', { name: 'Delete Iteration 1', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Compare results' }).click()
  await expect(page.getByLabel('Compared designs').getByRole('button', { name: /Iteration 1/ })).toHaveCount(0)
  const saved = normalizeState(await readState(page))
  const designs = page.locator('.platform-sidebar').getByRole('button', { name: 'My designs', exact: true })
  if (await designs.isVisible()) await designs.click()
  else await page.getByLabel('Navigate workspace').selectOption('My designs')
  await expect(page.getByRole('table', { name: 'Session test results' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Return to workbench' }).click()
  expect(normalizeState(await readState(page))).toEqual(saved)
  await audit(page)
})
